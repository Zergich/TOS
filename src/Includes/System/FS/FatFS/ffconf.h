/*---------------------------------------------------------------------------/
/  Конфигурации модуля FatFs (переведено)
/---------------------------------------------------------------------------*/

#define FFCONF_DEF 80386 /* ID ревизии */

/*---------------------------------------------------------------------------/
/ Конфигурации функций
/---------------------------------------------------------------------------*/

#define FF_FS_READONLY 0
/* Режим "только чтение". (0: Чтение/Запись, 1: Только чтение)
/  При 1 удаляются функции записи: f_write(), f_sync(), f_unlink(), f_mkdir(),
/  f_chmod(), f_rename(), f_truncate(), f_getfree(). */

#define FF_FS_MINIMIZE 0
/* Уровень минимизации — выкидывает часть базовых API ради экономии места.
/   0: Все функции включены.
/   1: Удалены f_stat(), f_getfree(), f_unlink(), f_mkdir(), f_truncate(),
/      f_rename().
/   2: Плюс к 1 удалены f_opendir(), f_readdir(), f_closedir().
/   3: Плюс к 2 удалена f_lseek(). */

#define FF_USE_FIND 0
/* Фильтрованный поиск по каталогу: f_findfirst() / f_findnext().
/  (0: выкл, 1: вкл, 2: вкл + поиск по альтернативному 8.3-имени) */

#define FF_USE_MKFS 0
/* Форматирование дисков изнутри ядра: f_mkfs(). (0: выкл, 1: вкл)
/  Понадобится, если захочешь форматировать диски сам, без host-машины. */

#define FF_USE_FASTSEEK 0
/* Быстрый seek (таблица кластеров в памяти для гигантских файлов). (0/1) */

#define FF_USE_EXPAND 0
/* f_expand() — выделить файлу непрерывную область (для стриминга). (0/1) */

#define FF_USE_CHMOD 0
/* Управление атрибутами и временем файлов: f_chmod(), f_utime(). (0/1)
/  Требует FF_FS_READONLY == 0. */

#define FF_USE_LABEL 0
/* Метки тома: f_getlabel(), f_setlabel(). (0/1) */

#define FF_USE_FORWARD 0
/* f_forward() — потоковое чтение без внутреннего буфера. (0/1) */

#define FF_USE_STRFUNC 0
#define FF_PRINT_LLI 0
#define FF_PRINT_FLOAT 0
#define FF_STRF_ENCODE 0
/* FF_USE_STRFUNC — строковые API: f_gets(), f_putc(), f_puts(), f_printf().
/   0: выкл. 1: вкл. 2: вкл + конвертация LF<->CRLF.
/  FF_PRINT_LLI=1 — f_printf() понимает long long. FF_PRINT_FLOAT — float.
/  FF_STRF_ENCODE — кодировка строк В ФАЙЛЕ при юникоде:
/   0: ANSI/OEM, 1: UTF-16LE, 2: UTF-16BE, 3: UTF-8. */

/*---------------------------------------------------------------------------/
/ Локаль и пространство имён
/---------------------------------------------------------------------------*/

#define FF_CODE_PAGE 437 /* ★ ИЗМЕНЕНО: было 932 (японская!). */
/* Кодовая страница OEM. Неверная страница ломает открытие файлов.
/  Нужна только для коротких 8.3-имён и томов без LFN.
/   437 - США (рекомендую)      866 - Русская (кириллица в SFN)
/   850 - Латиница-1            932/936/949/950 - японская/китайские/корейская
/   0   - включить ВСЕ страницы (огромный бинарник) */

#define FF_USE_LFN 2
#define FF_MAX_LFN 255
/* Поддержка длинных имён (LFN). FF_MAX_LFN — размер рабочего буфера для
/  ОДНОГО имени (в UTF-16 юнитах), 12..255, ставь 255.
/   0: выкл.
/   1: статический буфер в BSS. НЕ потоко-безопасно.
/   2: буфер на СТЕКЕ (текущий). Жрёт ~512 байт стека на вызов.
/   3: буфер на КУЧЕ. Требует ff_memalloc()/ff_memfree() (обёртки над
/      kmalloc/kfree). Возьми, если стек ядра маленький.
/  Для LFN в проект обязан входить ffunicode.c! */

#define FF_LFN_UNICODE 2 /* ★ ИЗМЕНЕНО: было 0. */
/* Кодировка строк в API (путей и имён).
/   0: ANSI/OEM, TCHAR = char (однобайтовая, как DOS)
/   1: UTF-16, TCHAR = WCHAR (сломает твой char*-код!)
/   2: UTF-8,  TCHAR = char  (★ как в Linux: код не меняется, но работает
/      вся юникод-кpagesа)
/   3: UTF-32, TCHAR = DWORD */

#define FF_LFN_BUF 768 /* ★ ИЗМЕНЕНО: было 255. */
#define FF_SFN_BUF 12
/* Размер поля fname[] в FILINFO (результат f_stat/f_readdir) — для ОДНОГО
/  имени, НЕ пути. В UTF-8 кириллица = 3 байта/символ, максимум имени
/  (255 юнитов) = 765 байт, поэтому 768. FF_SFN_BUF=12 — под 8.3-имя. */

#define FF_FS_RPATH 0
/* Относительные пути ВНУТРИ FatFs ("." и "..", cwd).
/   0: выкл (пути всегда от корня "0:/").
/   1: + f_chdir(), f_chdrive().
/   2: + f_getcwd().
/  У тебя пути резолвит твой VFS — оставляй 0, иначе два механизра путей
/  будут конфликтовать. */

#define FF_PATH_DEPTH 10
/* Максимальная глубина вложенности каталогов ТОЛЬКО для exFAT (FAT32 не
/  ограничена). На каждый уровень +24 байта к размеру FATFS-объекта. */

/*---------------------------------------------------------------------------/
/ Диски и тома
/---------------------------------------------------------------------------*/

#define FF_VOLUMES 1
/* Число логических томов (том = строка "0:", "1:"...). Диапазон 1-10.
/  Понадобится поднять, когда появится второй диск/раздел. */

#define FF_STR_VOLUME_ID 0
#define FF_VOLUME_STRS "RAM", "NAND", "CF", "SD", "SD2", "USB", "USB2", "USB3"
/* Именованные тома: вместо "0:" писать "sd:". Сравнение без учёта регистра.
/  0 = выкл (тома только по номерам). */

#define FF_MULTI_PARTITION 0
/* Несколько разделов на одном физическом диске (таблица VolToPart[],
/  + f_fdisk()). 0 = один том = один диск. */

#define FF_MIN_SS 512
#define FF_MAX_SS 512
/* Диапазон размеров сектора (512/1024/2048/4096). Оба 512 — для ATA/HDD/USB.
/  ЕСЛИ поставишь FF_MAX_SS > FF_MIN_SS — FatFs перейдёт в режим переменного
/  размера, и ты ОБЯЗАН реализовать GET_SECTOR_SIZE в disk_ioctl(). Пока
/  твой ATA читает по 512 — не трогай. */

#define FF_LBA64 1 /* ★ ИЗМЕНЕНО: было 0. Требует FF_FS_EXFAT=1 (включён). */
/* 64-битные LBA-адреса -> диски больше 2 ТБ. */

#define FF_MIN_GPT 0x10000000
/* Порог числа секторов для выбора GPT вместо MBR в f_mkfs()/f_fdisk().
/  Работает только при FF_LBA64=1. */

#define FF_USE_TRIM 0
/* ATA-TRIM (сообщение SSD, что блок не нужен). Требует CTRL_TRIM в
/  disk_ioctl(). */

/*---------------------------------------------------------------------------/
/ Системные конфигурации
/---------------------------------------------------------------------------*/

#define FF_FS_TINY 0
/* "Тощий" режим: убрать приватный буфер сектора из FIL, юзать общий из FATFS.
/  0: норм (быстрее), 1: tiny (меньше памяти на каждый открытый файл). */

#define FF_FS_EXFAT 1 /* ★ ИЗМЕНЕНО: было 0. Требует FF_USE_LFN>=1. */
/* Поддержка exFAT: файлы > 4 ГБ, тома огромные. Убирает совместимость с
/  ANSI C89 (тебе пофиг, у тебя gcc). FAT32-тома продолжают работать. */

#define FF_FS_NORTC 0
#define FF_NORTC_MON 1
#define FF_NORTC_MDAY 1
#define FF_NORTC_YEAR 2025
/* FF_FS_NORTC=0: метки времени настоящие, нужна get_fattime() (у тебя есть,
/  через GetTimeRTS). FF_FS_NORTC=1: метки фиксированные константы выше —
/  если RTC глючит, проще включить 1. */

#define FF_FS_CRTIME 0
/* 1 = в FILINFO доступно время СОЗДАНИЯ файла (доп. поле в каталоге). */

#define FF_FS_NOFSINFO 0
/* Доверие к FSINFO-сектору FAT32 (счётчик свободных кластеров):
/   bit0=1: не верить счётчику, f_getfree() делает полный скан FAT (медленно,
/            но точно после падения диска).
/   bit1=1: не верить номеру последнего кластера. */

#define FF_FS_LOCK 0
/* Блокировка файлов: запрет открыть один файл дважды / удалить открытый.
/   0: выкл — САМ следи, иначе порчишь том.
/  >0: вкл, число = сколько файлов можно держать под замком сразу.
/  Никаких внешних функций не требует. Включи, когда ядро станет
/  многозадачным. */

#define FF_FS_REENTRANT 0
#define FF_FS_TIMEOUT 1000
/* Потоко-безопасность FatFs (для SMP/многопоточности):
/   0: выкл — один поток за раз, иначе порча данных.
/   1: вкл — требует ff_mutex_create/delete/take/give() (ffsystem.c).
/  FF_FS_TIMEOUT — таймаут захвата мьютекса в тиках. */

/*--- Конец опций конфигурации ---*/
